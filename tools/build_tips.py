"""Convert the research report's "App tip library" section into app data (tips.js).

Usage: python tools/build_tips.py "<path to report.md>" app/src/main/assets/tips.js
"""
import json
import re
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()

refs = dict(re.findall(r"^\[([^\]]+)\]:\s*(\S+)", text, re.M))
lib = text.split("## App tip library", 1)[1]

CAT_META = {
    "Getting Started": ("start", "🚀"),
    "Settings": ("settings", "⚙️"),
    "Controls": ("controls", "🎮"),
    "Jason & Lucia": ("duo", "💞"),
    "Map": ("map", "🗺️"),
    "Money": ("money", "💵"),
    "Heists & Robberies": ("heists", "💎"),
    "Combat": ("combat", "🎯"),
    "Wanted Level": ("wanted", "🚨"),
    "Vehicles": ("vehicles", "🏎️"),
    "Side Activities": ("activities", "🌴"),
    "Easter Eggs": ("eggs", "🥚"),
    "Beginner Mistakes": ("mistakes", "⚠️"),
}

categories, tips = [], []
cat = None
lines = lib.splitlines()
i = 0
head_re = re.compile(r"^\*\*([A-Z]{2}-\d+) · (.+?)\*\*\s*\[(Confirmed|Reported|Unverified)\]")
while i < len(lines):
    line = lines[i]
    if line.startswith("### "):
        name = line[4:].strip()
        cid, icon = CAT_META.get(name, (re.sub(r"\W+", "-", name.lower()), "⭐"))
        cat = cid
        categories.append({"id": cid, "name": name, "icon": icon})
    m = head_re.match(line)
    if m and cat:
        body_lines = []
        i += 1
        while i < len(lines) and lines[i].strip() and not head_re.match(lines[i]) and not lines[i].startswith("#"):
            body_lines.append(lines[i].strip())
            i += 1
        body = " ".join(body_lines)
        sources = []
        sm = re.search(r"\s*Sources?:\s*(.*)$", body)
        if sm:
            for label, key in re.findall(r"\[([^\]]+)\]\[([^\]]+)\]", sm.group(1)):
                sources.append({"name": label, "url": refs.get(key, "")})
            body = body[: sm.start()].strip()
        conflict = "**Conflict:**" in body
        body = body.replace("**Conflict:**", "").strip()
        body = re.sub(r"\*\*(.+?)\*\*", r"\1", body)
        body = re.sub(r"\[([^\]]+)\]\[[^\]]+\]", r"\1", body)
        body = body[:1].upper() + body[1:]
        tips.append({
            "id": m.group(1), "cat": cat, "title": m.group(2).strip(),
            "conf": m.group(3), "conflict": conflict, "body": body, "sources": sources,
        })
        continue
    i += 1

data = {"categories": categories, "tips": tips}
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_tips.py — do not edit by hand.\n")
    f.write("window.TIPS_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(f"{len(categories)} categories, {len(tips)} tips -> {out}")
