"""Convert content/walkthrough.md into app data (walkthrough.js).

Format:
  ## Chapter title            -> a chapter (first paragraph after it = intro)
  ### Mission name [Confirmed|Reported|Unverified]
  Who: Jason | Lucia | Both
  Unlocks: comma, separated, list
  - step (repeatable)
  > Tip: text (repeatable)
  ! Missable: text (repeatable)
  Sources: Name <url>; Name <url>

Usage: python tools/build_walkthrough.py content/walkthrough.md app/src/main/assets/walkthrough.js
"""
import json
import re
import sys

src, out = sys.argv[1], sys.argv[2]
chapters = []
ch = mi = None
for raw in open(src, encoding="utf-8"):
    line = raw.rstrip("\n").strip()
    if not line or line.startswith("<!--") or line.startswith("# "):
        continue
    if line.startswith("## "):
        ch = {"title": line[3:].strip(), "intro": "", "missions": []}
        chapters.append(ch)
        mi = None
        continue
    if ch is None:
        continue
    m = re.match(r"^### (.+?)\s*\[(Confirmed|Reported|Unverified)\]\s*$", line)
    if m:
        mi = {"name": m.group(1).strip(), "conf": m.group(2), "who": "", "unlocks": [],
              "steps": [], "tips": [], "missable": [], "sources": []}
        ch["missions"].append(mi)
        continue
    if mi is None:
        ch["intro"] = (ch["intro"] + " " + line).strip()
        continue
    if line.startswith("Who:"):
        mi["who"] = line[4:].strip()
    elif line.startswith("Unlocks:"):
        mi["unlocks"] = [u.strip() for u in line[8:].split(",") if u.strip()]
    elif line.startswith("- "):
        mi["steps"].append(line[2:].strip())
    elif line.startswith("> Tip:"):
        mi["tips"].append(line[6:].strip())
    elif line.startswith("! Missable:"):
        mi["missable"].append(line[11:].strip())
    elif line.startswith("Sources:"):
        for part in line[8:].split(";"):
            pm = re.match(r"\s*(.+?)\s*<(\S+)>", part)
            if pm:
                mi["sources"].append({"name": pm.group(1), "url": pm.group(2)})

n = 0
for ci, c in enumerate(chapters):
    for mj, mm in enumerate(c["missions"]):
        n += 1
        mm["id"] = "M%03d" % n
        mm["no"] = n
data = {"chapters": chapters}
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_walkthrough.py — do not edit by hand.\n")
    f.write("window.WALK_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(f"{len(chapters)} chapters, {n} missions -> {out}")
